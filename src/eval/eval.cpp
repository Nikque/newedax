/** evaluation function error coefficients of the weights of Edax 4.4 and 4.5 */
static const double EVAL_ERROR_COEFFICIENT[6] = { -0.10026799, 0.31027733, -0.57772603, 0.07585621, 1.16492647, 5.4171698 };

/** header of an evaluation file */
typedef struct EvalFileHeader {
	int format;                  /**< 1: Edax 4 ("EDAX" "EVAL", or swapped bytes), 2: NEDXEVAL */
	bool swap;                   /**< weights of swapped bytes */
	unsigned int version, release, build;
	double date;
	int n_plies;                 /**< form 2: plies in the file */
	int n_group;                 /**< pattern groups of the weights: EVAL2_N_GROUP, or EVAL2_N_GROUP_ALL (extra groups) */
	unsigned int n_weights;      /**< weights of a ply */
	double coefficient[6];       /**< error coefficients A, B, C, a, b, c */
} EvalFileHeader;

/** @brief Write the first n pattern groups in the form of a file header. */
static void eval_groups_write(unsigned char *x, const int n)
{
	for (int i = 0; i < n; ++i, x += EVAL2_GROUP_SIZE) {
		memset(x, 0, EVAL2_GROUP_SIZE);
		x[0] = EVAL_GROUP[i].n_square;
		x[1] = EVAL_GROUP[i].n_place;
		memcpy(x + 4, &EVAL_GROUP[i].n_packed, 4);
		memcpy(x + 8, EVAL_GROUP[i].x, EVAL_GROUP[i].n_square);
	}
}

/**
 * @brief Read the header of an evaluation file (form 1 or 2); stop Edax if it cannot be used.
 *
 * @param f File, at its start; then at its first weight.
 * @param file File name.
 * @param h Header.
 */
static void eval_file_header_read(FILE *f, const char *file, EvalFileHeader *h)
{
	unsigned char magic[8];
	unsigned int edax_header, eval_header;
	int r;

	if (fread(magic, 1, 8, f) != 8) fatal_error("%s is not an Edax evaluation file\n", file);
	if (memcmp(magic, EVAL2_MAGIC, 8) == 0) {
		unsigned char x[EVAL2_HEADER_SIZE(EVAL2_N_GROUP_ALL)], groups[EVAL2_N_GROUP_ALL * EVAL2_GROUP_SIZE];
		unsigned short format, size, n_plies, first_ply, n_group;
		unsigned int flags, n_weights, crc, n_expected = 0;

		memcpy(x, magic, 8);
		if (fread(x + 8, 1, 4, f) != 4) fatal_error("Cannot read version info from %s\n", file);
		memcpy(&format, x + 8, 2);
		memcpy(&size, x + 10, 2);
		if (format != 2) fatal_error("%s is an evaluation file of another form (%u)\n", file, format);
		if (size != EVAL2_HEADER_SIZE(EVAL2_N_GROUP) && size != EVAL2_HEADER_SIZE(EVAL2_N_GROUP_ALL))
			fatal_error("%s holds weights of patterns this Edax does not use\n", file);
		if (fread(x + 12, 1, size - 12, f) != (size_t) (size - 12)) fatal_error("Cannot read version info from %s\n", file);
		memcpy(&crc, x + size - 4, 4);
		if (crc32c_bytes(0, x, size - 4) != crc) fatal_error("Damaged header in %s\n", file);
		memcpy(&flags, x + 12, 4);
		memcpy(&h->version, x + 16, 4);
		memcpy(&h->release, x + 20, 4);
		memcpy(&h->build, x + 24, 4);
		memcpy(&h->date, x + 28, 8);
		memcpy(&n_plies, x + 36, 2);
		memcpy(&first_ply, x + 38, 2);
		memcpy(&n_weights, x + 40, 4);
		memcpy(&n_group, x + 44, 2);
		memcpy(h->coefficient, x + 48, sizeof h->coefficient);
		eval_groups_write(groups, EVAL2_N_GROUP_ALL);
		for (int i = 0; i < n_group && i < EVAL2_N_GROUP_ALL; ++i) n_expected += EVAL_GROUP[i].n_packed;
		if (flags != 0 || (n_group != EVAL2_N_GROUP && n_group != EVAL2_N_GROUP_ALL) || size != EVAL2_HEADER_SIZE(n_group)
		 || n_weights != n_expected || memcmp(x + EVAL2_GROUPS_AT, groups, n_group * EVAL2_GROUP_SIZE) != 0)
			fatal_error("%s holds weights of patterns this Edax does not use\n", file);
		if (first_ply != 0 || n_plies < EVAL_N_2PLY * 2) fatal_error("%s does not hold the weights of plies 0 to %d\n", file, EVAL_N_2PLY * 2 - 1);
		h->format = 2;
		h->swap = false;
		h->n_plies = n_plies;
		h->n_group = n_group;
		h->n_weights = n_weights;
		return;
	}

	memcpy(&edax_header, magic, 4);
	memcpy(&eval_header, magic + 4, 4);
	if (!((edax_header == EDAX && eval_header == EVAL) || (edax_header == XADE && eval_header == LAVE))) fatal_error("%s is not an Edax evaluation file\n", file);
	r = fread(&h->version, sizeof (int), 1, f);
	r += fread(&h->release, sizeof (int), 1, f);
	r += fread(&h->build, sizeof (int), 1, f);
	r += fread(&h->date, sizeof (double), 1, f);
	if (r != 4) fatal_error("Cannot read version info from %s\n", file);
	h->format = 1;
	h->swap = (edax_header == XADE);
	if (h->swap) {
		h->version = bswap_int(h->version);
		h->release = bswap_int(h->release);
		h->build = bswap_int(h->build);
	}
	h->n_plies = 0; // (not told by the file)
	h->n_group = EVAL2_N_GROUP;
	h->n_weights = EVAL_N_PACKED;
	memcpy(h->coefficient, EVAL_ERROR_COEFFICIENT, sizeof h->coefficient);
}

/**
 * @brief Check the rest of an evaluation file of form 2: the weights not read yet and the trailer.
 *
 * @param f File, after the weights of read_plies plies.
 * @param file File name.
 * @param h Header.
 * @param crc CRC of the weights read.
 * @param w Room for the weights of a ply.
 */
static void eval_file_check_2(FILE *f, const char *file, const EvalFileHeader *h, unsigned int crc, const int read_plies, short *w)
{
	unsigned char t[8];
	unsigned int c;

	for (int ply = read_plies; ply < h->n_plies; ++ply) {
		if (fread(w, sizeof (short), h->n_weights, f) != h->n_weights) fatal_error("Cannot read evaluation weight from %s\n", file);
		crc = crc32c_bytes(crc, w, h->n_weights * sizeof (short));
	}
	if (fread(t, 1, 8, f) != 8) fatal_error("Cannot read evaluation weight from %s\n", file);
	memcpy(&c, t, 4);
	if (c != crc || memcmp(t + 4, EVAL2_END, 4) != 0 || fgetc(f) != EOF) fatal_error("Damaged evaluation file %s (the check of the weights fails)\n", file);
}

/**
 * @brief Convert an evaluation file of form 1 into form 2, or form 2 into form 1.
 *
 * The weights are copied as they are (the weights of every ply of the file, even the ones Edax does not use).
 *
 * @param in File to convert.
 * @param out File to write.
 * @return true on success.
 */
bool eval_convert(const char *in, const char *out)
{
	EvalFileHeader h;
	FILE *f, *g;
	short *w = NULL;
	long long n_plies = 0, i;
	unsigned int crc = 0;
	bool ok = false;

	f = file_open(in, "rb");
	if (f == NULL) { error("Cannot open %s\n", in); return false; }
	eval_file_header_read(f, in, &h);
	if (h.format == 2) {
		n_plies = h.n_plies;
		if (h.n_group != EVAL2_N_GROUP) { error("%s holds weights that form 1 cannot hold\n", in); fclose(f); return false; }
	} else { // the plies that are left in the file
		long long here, end;
#ifdef _WIN32
		here = _ftelli64(f); _fseeki64(f, 0, SEEK_END); end = _ftelli64(f); _fseeki64(f, here, SEEK_SET);
#else
		here = ftello(f); fseeko(f, 0, SEEK_END); end = ftello(f); fseeko(f, here, SEEK_SET);
#endif
		if (here < 0 || end < here || (end - here) % (EVAL_N_PACKED * sizeof (short)) != 0 || end == here) {
			error("%s does not hold whole plies of weights\n", in);
			fclose(f);
			return false;
		}
		n_plies = (end - here) / (EVAL_N_PACKED * sizeof (short));
		if (n_plies > 65535) { error("%s holds too many plies\n", in); fclose(f); return false; }
	}
	w = (short*) malloc((size_t) n_plies * EVAL_N_PACKED * sizeof (short));
	if (w == NULL) { error("Cannot allocate the weights of %s\n", in); fclose(f); return false; }
	if (fread(w, sizeof (short) * EVAL_N_PACKED, (size_t) n_plies, f) != (size_t) n_plies) {
		error("Cannot read evaluation weight from %s\n", in);
		goto convert_end;
	}
	if (h.format == 2) {
		unsigned char t[8];
		unsigned int c;
		crc = crc32c_bytes(0, w, (size_t) n_plies * EVAL_N_PACKED * sizeof (short));
		if (fread(t, 1, 8, f) != 8 || (memcpy(&c, t, 4), c != crc) || memcmp(t + 4, EVAL2_END, 4) != 0 || fgetc(f) != EOF) {
			error("Damaged evaluation file %s (the check of the weights fails)\n", in);
			goto convert_end;
		}
	} else if (h.swap) {
		for (i = 0; i < n_plies * EVAL_N_PACKED; ++i) w[i] = bswap_short(w[i]);
	}

	g = file_open(out, "wb");
	if (g == NULL) { error("Cannot open %s\n", out); goto convert_end; }
	if (h.format == 1) { // into form 2
		unsigned char x[EVAL2_HEADER_SIZE(EVAL2_N_GROUP)] = {};
		const unsigned short format = 2, size = EVAL2_HEADER_SIZE(EVAL2_N_GROUP), plies = (unsigned short) n_plies, first_ply = 0, n_group = EVAL2_N_GROUP;
		const unsigned int n_weights = EVAL_N_PACKED;
		unsigned char t[8];
		memcpy(x, EVAL2_MAGIC, 8);
		memcpy(x + 8, &format, 2);
		memcpy(x + 10, &size, 2);
		memcpy(x + 16, &h.version, 4);
		memcpy(x + 20, &h.release, 4);
		memcpy(x + 24, &h.build, 4);
		memcpy(x + 28, &h.date, 8);
		memcpy(x + 36, &plies, 2);
		memcpy(x + 38, &first_ply, 2);
		memcpy(x + 40, &n_weights, 4);
		memcpy(x + 44, &n_group, 2);
		memcpy(x + 48, h.coefficient, sizeof h.coefficient);
		eval_groups_write(x + EVAL2_GROUPS_AT, EVAL2_N_GROUP);
		crc = crc32c_bytes(0, x, size - 4);
		memcpy(x + size - 4, &crc, 4);
		crc = crc32c_bytes(0, w, (size_t) n_plies * EVAL_N_PACKED * sizeof (short));
		memcpy(t, &crc, 4);
		memcpy(t + 4, EVAL2_END, 4);
		ok = fwrite(x, 1, size, g) == size
		  && fwrite(w, sizeof (short) * EVAL_N_PACKED, (size_t) n_plies, g) == (size_t) n_plies
		  && fwrite(t, 1, 8, g) == 8;
	} else { // into form 1
		const unsigned int header[5] = { (unsigned int) EDAX, (unsigned int) EVAL, h.version, h.release, h.build };
		ok = fwrite(header, sizeof header, 1, g) == 1
		  && fwrite(&h.date, sizeof h.date, 1, g) == 1
		  && fwrite(w, sizeof (short) * EVAL_N_PACKED, (size_t) n_plies, g) == (size_t) n_plies;
		if (memcmp(h.coefficient, EVAL_ERROR_COEFFICIENT, sizeof h.coefficient) != 0)
			warn("%s: the error coefficients of %s are not kept (form 1 does not hold them)\n", out, in);
	}
	if (fclose(g) != 0) ok = false;
	if (!ok) { error("Cannot write %s\n", out); file_remove(out); }

convert_end:
	free(w);
	fclose(f);
	return ok;
}

/**
 * @brief Load the evaluation function features' weights.
 *
 * The weights are stored in a global variable, because, once loaded from the
 * file, they stay constant during the lifetime of the program. As loading
 * the weights is time & resource consuming, a counter variable check that
 * the weights are effectively loaded only once.
 *
 * @param file File name of the evaluation function data.
 */
void eval_open(const char* file)
{
	EvalFileHeader header;
	unsigned int crc = 0;
	int n_w;
	int *T;
	int ply, i, j, k;
	int r;
	FILE* f;
	short *w;
	Eval_weight *pe;
	SymetryPacking (*P)[2];
	SymetryPacking *pp;
	static const int kd_S10[] = { 19683, 6561, 2187, 729, 243, 81, 27, 9, 3, 1 };
	static const int kd_C10[] = { 19683, 6561, 2187, 729, 81, 243, 27, 9, 3, 1 };
	static const int kd_C9[] = { 1, 9, 3, 81, 27, 243, 2187, 729, 6561 };

	if (EVAL_LOADED) {
		// the same file (libedax initialized again): the weights are kept; another file: it is loaded
		if (EVAL_FILE != NULL && file != NULL && strcmp(EVAL_FILE, file) == 0) { ++EVAL_LOADED; return; }
		eval_close();
	}
	EVAL_LOADED = 1;

	// the following is assumed:
	//	-(unsigned) int are 32 bits
	if (sizeof (int) != 4) fatal_error("int size is not compatible with Edax.\n");
	//	-(unsigned) short are 16 bits
	if (sizeof (short) != 2) fatal_error("short size is not compatible with Edax.\n");

	// create unpacking tables
	OPPONENT_FEATURE = (unsigned short *) malloc(59049 * sizeof(unsigned short));	// 3^10
	P = (SymetryPacking (*)[2]) malloc(sizeof(*P)); // (*P is the 2 tables: up to v4.5.5-nikque.15 twice their size)
	T = (int *) malloc(2 * 59049 * sizeof(*T));
	if ((OPPONENT_FEATURE == NULL) || (P == NULL) || (T == NULL))
		fatal_error("Cannot allocate temporary table variable.\n");

	set_opponent_feature(OPPONENT_FEATURE, 0, 10);

	set_eval_packing((*P)[0].EVAL_S8, T, kd_S10 + 2, 0, 0, 0, 8);	/* 8 squares : 6561 -> 3321 */
	for (j = 0; j < 6561; ++j)
		(*P)[1].EVAL_S8[j] = (*P)[0].EVAL_S8[OPPONENT_FEATURE[j + 26244]];	// 1100000000(3)

	set_eval_packing((*P)[0].EVAL_S7, T, kd_S10 + 3, 0, 0, 0, 7);	/* 7 squares : 2187 -> 1134 */
	for (j = 0; j < 2187; ++j)
		(*P)[1].EVAL_S7[j] = (*P)[0].EVAL_S7[OPPONENT_FEATURE[j + 28431]];	// 1110000000(3)

	set_eval_packing((*P)[0].EVAL_S6, T, kd_S10 + 4, 0, 0, 0, 6);	/* 6 squares : 729 -> 378 */
	for (j = 0; j < 729; ++j)
		(*P)[1].EVAL_S6[j] = (*P)[0].EVAL_S6[OPPONENT_FEATURE[j + 29160]];	// 1111000000(3)

	set_eval_packing((*P)[0].EVAL_S5, T, kd_S10 + 5, 0, 0, 0, 5);	/* 5 squares : 243 -> 135 */
	for (j = 0; j < 243; ++j)
		(*P)[1].EVAL_S5[j] = (*P)[0].EVAL_S5[OPPONENT_FEATURE[j + 29403]];	// 1111100000(3)

	set_eval_packing((*P)[0].EVAL_S4, T, kd_S10 + 6, 0, 0, 0, 4);	/* 4 squares : 81 -> 45 */
	for (j = 0; j < 81; ++j)
		(*P)[1].EVAL_S4[j] = (*P)[0].EVAL_S4[OPPONENT_FEATURE[j + 29484]];	// 1111110000(3)

	set_eval_packing((*P)[0].EVAL_C9, T, kd_C9, 0, 0, 0, 9);	/* 9 corner squares : 19683 -> 10206 */
	for (j = 0; j < 19683; ++j)
		(*P)[1].EVAL_C9[j] = (*P)[0].EVAL_C9[OPPONENT_FEATURE[j + 19683]];	// 1000000000(3)

	set_eval_packing((*P)[0].EVAL_S10, T, kd_S10, 0, 0, 0, 10);	/* 10 squares (edge + X) : 59049 -> 29646 */
	set_eval_packing((*P)[0].EVAL_C10, T, kd_C10, 0, 0, 0, 10);	/* 10 squares (angle + X) : 59049 -> 29889 */
	for (j = 0; j < 59049; ++j) {
		(*P)[1].EVAL_S10[j] = (*P)[0].EVAL_S10[OPPONENT_FEATURE[j]];
		(*P)[1].EVAL_C10[j] = (*P)[0].EVAL_C10[OPPONENT_FEATURE[j]];
	}

	free(T);

	// allocation
	EVAL_WEIGHT = (Eval_weight(*)[EVAL_N_2PLY - 1]) malloc(sizeof(*EVAL_WEIGHT));
	if (EVAL_WEIGHT == NULL) fatal_error("Cannot allocate evaluation weights.\n");

	// data reading
	f = file_open(file, "rb");
	if (f == NULL) {
		fprintf(stderr, "Cannot open %s", file);
		exit(EXIT_FAILURE);
	}

	// File header
	eval_file_header_read(f, file, &header);
	n_w = (int) header.n_weights;
	w = (short*) malloc(n_w * sizeof (*w)); // a temporary to read packed weights
	if (w == NULL) fatal_error("Cannot allocate temporary table variable.\n");
	// Weights : read & unpack them
	for (ply = 0; ply < EVAL_N_2PLY * 2; ply++) {
		r = fread(w, sizeof (short), n_w, f);
		if (r != n_w) fatal_error("Cannot read evaluation weight from %s\n", file);
		if (header.format == 2) crc = crc32c_bytes(crc, w, n_w * sizeof (short));
		if (ply < 2) continue;	// skip ply 1 & 2

		if (header.swap) for (i = 0; i < n_w; ++i) w[i] = bswap_short(w[i]);

		pe = (Eval_weight *)((*EVAL_WEIGHT)[(ply - 2) >> 1].S0 + (ply & 1));
		pp = *P + (ply & 1);
		for (k = 0; k < 19683; k++) {
			*(pe->C9[k]) = w[pp->EVAL_C9[k] + EVAL_PACKED_OFS[0]];
		}
		for (k = 0; k < 59049; k++) {
			*(pe->C10[k]) = w[pp->EVAL_C10[k] + EVAL_PACKED_OFS[1]];
			i = pp->EVAL_S10[k];
			*(pe->S100[k]) = w[i + EVAL_PACKED_OFS[2]];
			*(pe->S101[k]) = w[i + EVAL_PACKED_OFS[3]];
		}
		for (k = 0; k < 6561; k++) {
			i = pp->EVAL_S8[k];
			*(pe->S8x4[k]) = w[i + EVAL_PACKED_OFS[4]];
			*(pe->S8x4[k + 6561]) = w[i + EVAL_PACKED_OFS[5]];
			*(pe->S8x4[k + 13122]) = w[i + EVAL_PACKED_OFS[6]];
			*(pe->S8x4[k + 19683]) = w[i + EVAL_PACKED_OFS[7]];
		}
		for (k = 0; k < 2187; k++) {
			*(pe->S7654[k]) = w[pp->EVAL_S7[k] + EVAL_PACKED_OFS[8]];
		}
		for (k = 0; k < 729; k++) {
			*(pe->S7654[k + 2187]) = w[pp->EVAL_S6[k] + EVAL_PACKED_OFS[9]];
		}
		for (k = 0; k < 243; k++) {
			*(pe->S7654[k + 2916]) = w[pp->EVAL_S5[k] + EVAL_PACKED_OFS[10]];
		}
		for (k = 0; k < 81; k++) {
			*(pe->S7654[k + 3159]) = w[pp->EVAL_S4[k] + EVAL_PACKED_OFS[11]];
		}
		*(pe->S0) = w[EVAL_PACKED_OFS[12]];
#if EVAL_SLOTS > 48
		// extra groups: the file weights (from the side to move at an even ply), or 0 if the file has none
		for (i = 0; i < 4; ++i) {
			const short *wx = w + EVAL_N_PACKED + i * EVAL_N_X;
			if (n_w == EVAL_N_PACKED) for (k = 0; k < EVAL_N_X; k++) *(pe->X[i][k]) = 0;
			else if (ply & 1) for (k = 0; k < EVAL_N_X; k++) *(pe->X[i][k]) = wx[OPPONENT_FEATURE[k]];
			else for (k = 0; k < EVAL_N_X; k++) *(pe->X[i][k]) = wx[k];
		}
#endif
	}

	if (header.format == 2) eval_file_check_2(f, file, &header, crc, EVAL_N_2PLY * 2, w);
	fclose(f);
	free(w);
	free(P);

	EVAL_A = header.coefficient[0], EVAL_B = header.coefficient[1], EVAL_C = header.coefficient[2];
	EVAL_a = header.coefficient[3], EVAL_b = header.coefficient[4], EVAL_c = header.coefficient[5];

	info("<Evaluation function weights version %u.%u.%u loaded>\n", header.version, header.release, header.build);
	EVAL_FILE = file ? string_duplicate(file) : NULL;

	// f = file_open("eval.bin", "wb");
	// fwrite(*EVAL_WEIGHT, sizeof(Eval_weight), EVAL_N_PLY, f);
	// fclose(f);
}

